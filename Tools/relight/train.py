"""Trains the neural grade: a tiny network that learns the teacher's light and colour changes.

    Tools/relight/.venv/bin/python Tools/relight/train.py --teacher s0.35 [--steps 4000]

Design (HDRNet-style bilateral grid; Gharbi et al. 2017):
  - A small CNN looks at a 256x144 copy of the frame and predicts a grid of colour transforms:
    16 x 9 cells across the picture x 8 brightness levels, each a 3x4 affine matrix (RGB -> RGB).
  - At full resolution each pixel looks up its transform in the grid by position and brightness
    (trilinear) and applies it to its own colour.
So the output can only change light and colour smoothly, never move or invent pixels: no smearing,
and it's cheap (the CNN runs on 37k pixels; the full-res part is one lookup and a 3x4 multiply).

Works in the recordings' SDR domain (sRGB-encoded BT.709); the app converts HDR frames into the same
domain and back. Loss compares the student with the teacher on blurred 1/4-size images, so the
teacher's small changes to fine detail (which the student can't and shouldn't copy) don't count.

Writes Tools/relight/data/grade.pt and the app's weights file Sources/PS5Stream/NeuralGradeWeights.swift.
"""

import argparse
import base64
import pathlib
import random

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from PIL import Image

GW, GH, GD = 16, 9, 8   # grid cells across, down, brightness levels
LW, LH = 256, 144       # low-res input
CROP = (256, 448)       # training crop (height, width) from frames resized to 512 wide


class Grade(nn.Module):
    def __init__(self):
        super().__init__()
        c = [3, 16, 32, 64, 64]
        # 256x144 -> 128x72 -> 64x36 -> 32x18 -> 16x9
        self.down = nn.ModuleList(nn.Conv2d(c[i], c[i + 1], 3, 2, 1) for i in range(4))
        self.local = nn.Sequential(nn.Conv2d(64, 64, 3, 1, 1), nn.ReLU(), nn.Conv2d(64, 64, 3, 1, 1))
        # Global scene context (time of day, overall exposure): pooled features -> per-channel bias.
        self.glob = nn.Sequential(nn.Linear(64, 64), nn.ReLU(), nn.Linear(64, 64))
        self.out = nn.Conv2d(64, GD * 12, 1)
        # Start at the identity transform, so training begins from "no change".
        nn.init.zeros_(self.out.weight)
        with torch.no_grad():
            ident = torch.zeros(GD, 3, 4)
            ident[:, 0, 0] = ident[:, 1, 1] = ident[:, 2, 2] = 1
            self.out.bias.copy_(ident.reshape(-1))

    def grid(self, low):
        x = low
        for conv in self.down:
            x = F.relu(conv(x))
        g = self.glob(x.mean(dim=(2, 3)))
        x = F.relu(self.local(x) + g[:, :, None, None])
        return self.out(x)  # B, GD*12, GH, GW

    def forward(self, img):
        low = F.interpolate(img, size=(LH, LW), mode="bilinear", align_corners=False, antialias=True)
        self.last_grid = self.grid(low)
        return apply_grid(self.last_grid, img)


def guide(img):
    return (img * torch.tensor([0.2126, 0.7152, 0.0722], device=img.device)[None, :, None, None]).sum(1)


def apply_grid(grid, img):
    """Trilinear lookup of each pixel's 3x4 transform (x, y, brightness), then apply it."""
    b, _, h, w = img.shape
    g = grid.view(b, GD, 12, GH, GW).permute(0, 2, 1, 3, 4)  # B, 12, D, H, W
    ys = torch.linspace(-1, 1, h, device=img.device)
    xs = torch.linspace(-1, 1, w, device=img.device)
    yy, xx = torch.meshgrid(ys, xs, indexing="ij")
    z = guide(img) * 2 - 1
    coords = torch.stack([xx.expand(b, h, w), yy.expand(b, h, w), z], dim=-1)[:, None]  # B,1,H,W,3
    coef = F.grid_sample(g, coords, mode="bilinear", padding_mode="border", align_corners=True)[:, :, 0]
    A = coef.view(b, 3, 4, h, w)
    return (A[:, :, :3] * img[:, None]).sum(2) + A[:, :, 3]


def load(p, size=None):
    im = Image.open(p).convert("RGB")
    if size:
        im = im.resize(size, Image.BICUBIC)
    return torch.from_numpy(np.asarray(im, dtype=np.float32) / 255).permute(2, 0, 1)


def blur_small(x):
    x = F.interpolate(x, scale_factor=0.25, mode="bilinear", align_corners=False, antialias=True)
    return F.avg_pool2d(F.pad(x, (1, 1, 1, 1), mode="replicate"), 3, 1)


def export(model, path):
    """fp16 weights, base64 in a Swift string (a float array literal this size would stall the compiler)."""
    tensors = []
    for name, t in model.state_dict().items():
        tensors.append((name, list(t.shape), t.detach().cpu().numpy().astype(np.float16)))
    blob = b"".join(a.tobytes() for _, _, a in tensors)
    layout = "\n".join(f"//   {n}: {s}" for n, s, _ in tensors)
    b64 = base64.b64encode(blob).decode()
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    body = "\n".join(lines)
    path.write_text(f"""// Generated by Tools/relight/train.py: neural grade weights (fp16, {len(blob) // 2} values), in order:
{layout}

let neuralGradeWeights = \"\"\"
{body}
\"\"\"
""")


def main():
    root = pathlib.Path(__file__).parent / "data"
    ap = argparse.ArgumentParser()
    ap.add_argument("--teacher", default="s0.35")
    ap.add_argument("--steps", type=int, default=4000)
    ap.add_argument("--size", type=int, default=512, help="training crop width")
    ap.add_argument("--smooth", type=float, default=0.05, help="grid smoothness weight")
    args = ap.parse_args()
    dev = "mps" if torch.backends.mps.is_available() else "cpu"

    tdir = root / "teacher" / args.teacher
    pairs = [(root / "frames" / p.name, p) for p in sorted(tdir.glob("*.png")) if (root / "frames" / p.name).exists()]
    random.seed(0)
    random.shuffle(pairs)
    val = pairs[: max(len(pairs) // 10, 1)]
    train = pairs[len(val):] or val
    print(f"{len(train)} training pairs, {len(val)} held out")

    def batch(items):
        xs, ys = [], []
        for a, b in items:
            x, y = load(a), load(b)
            _, h, w = x.shape
            s = args.size
            sh = int(s * h / w) // 16 * 16
            x = F.interpolate(x[None], size=(sh, s), mode="bilinear", antialias=True)[0]
            y = F.interpolate(y[None], size=(sh, s), mode="bilinear", antialias=True)[0]
            xs.append(x); ys.append(y)
        return torch.stack(xs).to(dev), torch.stack(ys).to(dev)

    cache = {p: batch([p]) for p in train + val}  # small set: keep it in memory
    model = Grade().to(dev)
    opt = torch.optim.AdamW(model.parameters(), lr=2e-3, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=2e-3, total_steps=args.steps)
    for step in range(1, args.steps + 1):
        items = random.sample(train, min(8, len(train)))
        # Same-size random crops (frames are landscape or, from split-screen recordings, portrait halves).
        xs, ys = [], []
        for i in items:
            cx, cy = cache[i]
            _, _, h, w = cx.shape
            top, left = random.randint(0, h - CROP[0]), random.randint(0, w - CROP[1])
            xs.append(cx[:, :, top:top + CROP[0], left:left + CROP[1]]); ys.append(cy[:, :, top:top + CROP[0], left:left + CROP[1]])
        x, y = torch.cat(xs), torch.cat(ys)
        if random.random() < 0.5:
            x, y = x.flip(-1), y.flip(-1)
        out = model(x)
        # Smoothness: neighbouring cells (across the picture and across brightness) should hold similar
        # transforms. The teacher's targets are noisy; without this the grid turns patchy (blotches).
        g = model.last_grid.view(-1, GD, 12, GH, GW)
        tv = ((g[:, 1:] - g[:, :-1]).abs().mean() + (g[..., 1:, :] - g[..., :-1, :]).abs().mean()
              + (g[..., 1:] - g[..., :-1]).abs().mean())
        loss = F.l1_loss(blur_small(out), blur_small(y)) + args.smooth * tv
        opt.zero_grad(); loss.backward(); opt.step(); sched.step()
        if step % 250 == 0 or step == 1:
            with torch.no_grad():
                vl = sum(F.l1_loss(blur_small(model(cache[i][0])), blur_small(cache[i][1])).item() for i in val) / len(val)
                base = sum(F.l1_loss(blur_small(cache[i][0]), blur_small(cache[i][1])).item() for i in val) / len(val)
            print(f"step {step}: train {loss.item():.4f}  held-out {vl:.4f} (no change: {base:.4f})", flush=True)

    torch.save(model.state_dict(), root / "grade.pt")
    export(model, pathlib.Path(__file__).parents[2] / "Sources/PS5Stream/NeuralGradeWeights.swift")
    n = sum(p.numel() for p in model.parameters())
    print(f"saved {n} parameters ({n * 2 / 1024:.0f} KB as fp16)")


if __name__ == "__main__":
    main()
